--  2026-09-14  目的地池：端口列支持规格（全部 / 区间 / 多段）
--  背景：dest_pool.port 由 INT 改为 VARCHAR，使端口字段可表达：
--        - 留空           => 全部端口
--        - 80             => 单端口
--        - 100-200        => 区间
--        - 9,100-200      => 多段（中英文逗号均可，由后端归一化）
--  幂等：重复执行安全；既有数字值会被自动转为字符串（3306 -> "3306"）。
--  执行： mysql -h <host> -P <port> -u <user> -p <db> < 2026-09-14-port-spec.sql
-- =============================================================
ALTER TABLE dest_pool
  MODIFY COLUMN port VARCHAR(64) NOT NULL DEFAULT ''
  COMMENT '端口规格：空=全部端口；支持单端口/区间/逗号分隔，如 9,100-200';
